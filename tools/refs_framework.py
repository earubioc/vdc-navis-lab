"""Check the Navisworks API DLLs that the add-in compiles against: are they there, and which .NET target do they declare?

  python tools/refs_framework.py <year> [--refs addin/refs]

The add-in is built for net48 (net48 is what Navisworks Manage 2025 and 2026 declare). A year whose DLLs are missing, or declare
another framework, is not compiled: the build stops and says what is needed. The DLLs are Autodesk's: they are read here, never
copied into the repository (addin/refs/ is git-ignored).
Exit codes: 0 all four present and net48; 3 missing DLLs; 4 a different framework.
"""
from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

REQUIRED = ["Autodesk.Navisworks.Api.dll", "Autodesk.Navisworks.Clash.dll", "Autodesk.Navisworks.ComApi.dll", "Autodesk.Navisworks.Interop.ComApi.dll"]
WANT = ".NETFramework,Version=v4.8"
ATTR = re.compile(rb"\.NET(?:Framework|CoreApp|Standard),Version=v[0-9.]+")


def target_of(path: Path) -> str | None:
    """The TargetFrameworkAttribute string, when the assembly carries one (an interop assembly generated by tlbimp does not)."""
    m = ATTR.search(path.read_bytes())
    return m.group(0).decode("ascii") if m else None


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("year")
    ap.add_argument("--refs", default=str(Path(__file__).resolve().parents[1] / "addin" / "refs"))
    a = ap.parse_args(argv)
    folder = Path(a.refs) / a.year
    missing = [n for n in REQUIRED if not (folder / n).is_file()]
    if missing:
        print(f"{a.year}: FALTAN {len(missing)} de {len(REQUIRED)} DLL en la carpeta de referencias:")
        for n in missing:
            print(f"  - {n}")
        print(f"Copiarlas desde la instalacion de Navisworks Manage {a.year} (carpeta del programa) a esa carpeta; no se versionan.")
        return 3
    other = 0
    for n in REQUIRED:
        t = target_of(folder / n)
        flag = "" if t in (WANT, None) else "   <-- NO es net48"
        other += bool(flag)
        print(f"{a.year}: {n:<40} {t or 'sin atributo (interop generado)'}{flag}")
    if other:
        print(f"{a.year}: la API declara otro framework; el add-in net48 no se compila contra ella sin una decision de Edgar.")
        return 4
    print(f"{a.year}: las {len(REQUIRED)} DLL estan y declaran net48.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
